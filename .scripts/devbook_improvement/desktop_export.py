"""Experimental isolated macOS desktop renderer for the official Syncer export.

This launches genuine Obsidian, not a headless replacement. Profile bootstrap is
based on the repository's verified disposable-vault harness; hosted operation
still requires an actual pilot. Generated bytes remain owned by Quartz Syncer.
"""
from __future__ import annotations

import argparse
import contextlib
import ctypes
import datetime as dt
import hashlib
import json
import os
from pathlib import Path
import plistlib
import re
import shlex
import shutil
import signal
import subprocess
import sys
import tempfile
import time
from typing import Any, Iterator, Mapping

from . import sync_export

PLUGINS = ('datacore', 'tabsdown', 'obsidian-excalidraw-plugin', 'quartz-syncer')
BUNDLE_FILES = ('main.js', 'manifest.json', 'styles.css')
APP_FLAGS = ('--use-mock-keychain', '--disable-background-networking', '--host-rules=MAP * 0.0.0.0, EXCLUDE localhost',
             '--disable-gpu', '--disable-background-timer-throttling',
             '--disable-renderer-backgrounding', '--disable-backgrounding-occluded-windows')


def _version(value: Any) -> tuple[int, int, int]:
    if not isinstance(value, str) or not re.fullmatch(r'\d+\.\d+\.\d+', value):
        raise ValueError('desktop export requires a numeric major.minor.patch application version')
    return tuple(int(part) for part in value.split('.'))


def validate_app_version(app_bundle: Path, settings: Path) -> str:
    with (app_bundle / 'Contents/Info.plist').open('rb') as stream:
        version = plistlib.load(stream).get('CFBundleShortVersionString')
    bundled = _version(version)
    for plugin in PLUGINS:
        manifest = settings / 'plugins' / plugin / 'manifest.json'
        if manifest.is_symlink() or not manifest.is_file():
            raise ValueError(f'missing regular export plugin manifest: {plugin}')
        required = json.loads(manifest.read_text()).get('minAppVersion')
        if bundled < _version(required):
            raise ValueError(f'bundled Obsidian {version} is older than {plugin} minimum {required}; '
                             'the isolated profile cannot use updates from the personal profile')
    return version


def _git(root: Path, *args: str, env: Mapping[str, str] | None = None) -> bytes:
    return subprocess.check_output(['git', *args], cwd=root, env=env, stderr=subprocess.PIPE)


def _source_hashes(root: Path) -> dict[str, str]:
    result = {}
    for record in _git(root, 'ls-files', '-z', '--', 'Vault').split(b'\0'):
        if not record:
            continue
        name = os.fsdecode(record)
        if name.startswith('Vault/.obsidian/'):
            continue
        path = root / name
        if path.is_symlink() or not path.is_file():
            raise ValueError(f'export source must be a regular file: {name}')
        result[name] = hashlib.sha256(path.read_bytes()).hexdigest()
    return result


def _date_ns(value: str) -> int:
    parsed = dt.datetime.fromisoformat(value.strip().strip('"\'').replace('Z', '+00:00'))
    if parsed.tzinfo is None:
        raise ValueError('export timestamp requires a timezone')
    parsed = parsed.astimezone(dt.timezone.utc)
    epoch = dt.datetime(1970, 1, 1, tzinfo=dt.timezone.utc)
    delta = parsed - epoch
    return (delta.days * 86400 + delta.seconds) * 1_000_000_000 + delta.microseconds * 1000


def _baseline_dates(path: Path) -> dict[str, int]:
    if not path.is_file():
        return {}
    if path.is_symlink():
        raise ValueError('generated baseline cannot be a symlink')
    text = path.read_text(encoding='utf-8')
    match = re.match(r'\A---\r?\n(.*?)\r?\n---(?:\r?\n|\Z)', text, re.S)
    if not match:
        return {}
    values = {}
    for key, value in re.findall(r'(?m)^(created|modified):[ \t]*(.+?)\s*$', match.group(1)):
        if key in values:
            raise ValueError('duplicate generated timestamp')
        values[key] = _date_ns(value)
    return values


def _commit(root: Path, path: str, *, first: bool = False) -> tuple[str, int]:
    rows = _git(root, 'log', '--format=%H %ct', '--follow', '--', path).decode().splitlines()
    if not rows:
        raise ValueError(f'tracked export source has no Git history: {path}')
    sha, seconds = rows[-1 if first else 0].split()
    return sha, int(seconds) * 1_000_000_000


def _set_file_times(path: Path, created_ns: int, modified_ns: int) -> None:
    """Use Darwin's documented setattrlist API; retain millisecond precision."""
    if sys.platform != 'darwin':
        raise ValueError('desktop export timestamp materialization requires macOS')
    if path.is_symlink() or not path.is_file():
        raise ValueError('timestamp target must be a regular file')

    class AttrList(ctypes.Structure):
        _fields_ = [('bitmapcount', ctypes.c_uint16), ('reserved', ctypes.c_uint16),
                    ('commonattr', ctypes.c_uint32), ('volattr', ctypes.c_uint32),
                    ('dirattr', ctypes.c_uint32), ('fileattr', ctypes.c_uint32),
                    ('forkattr', ctypes.c_uint32)]

    class Timespec(ctypes.Structure):
        _fields_ = [('tv_sec', ctypes.c_long), ('tv_nsec', ctypes.c_long)]

    os.utime(path, ns=(modified_ns, modified_ns), follow_symlinks=False)
    attributes = AttrList(5, 0, 0x00000200, 0, 0, 0, 0)  # ATTR_CMN_CRTIME
    timestamp = Timespec(*divmod(created_ns, 1_000_000_000))
    library = ctypes.CDLL(None, use_errno=True)
    setter = library.setattrlist
    setter.argtypes = [ctypes.c_char_p, ctypes.POINTER(AttrList), ctypes.c_void_p,
                       ctypes.c_size_t, ctypes.c_ulong]
    setter.restype = ctypes.c_int
    if setter(os.fsencode(path), ctypes.byref(attributes), ctypes.byref(timestamp),
              ctypes.sizeof(timestamp), 0) != 0:
        error = ctypes.get_errno()
        raise OSError(error, os.strerror(error), str(path))
    observed = path.stat()
    birth_ns = getattr(observed, 'st_birthtime_ns', None)
    birth_ms = birth_ns // 1_000_000 if birth_ns is not None else round(observed.st_birthtime * 1000)
    if birth_ms != created_ns // 1_000_000 or observed.st_mtime_ns // 1_000_000 != modified_ns // 1_000_000:
        raise ValueError(f'filesystem cannot preserve export timestamps: {path.name}')


def materialize_timestamps(root: Path) -> None:
    for name in _source_hashes(root):
        source = root / name
        source_commit, modified = _commit(root, name)
        created = _commit(root, name, first=True)[1]
        if name.startswith('Vault/Home/') and name.endswith('.md'):
            output_name = 'Web/content/' + name.removeprefix('Vault/Home/')
            dates = _baseline_dates(root / output_name)
            created = dates.get('created', created)
            if 'modified' in dates:
                output_history = _git(root, 'log', '-1', '--format=%H', '--', output_name).decode().strip()
                if output_history:
                    relation = subprocess.run(['git', 'merge-base', '--is-ancestor', source_commit, output_history],
                                              cwd=root, capture_output=True, check=False)
                    if relation.returncode not in (0, 1):
                        raise ValueError('cannot establish source/export timestamp ancestry')
                    if relation.returncode == 0:
                        modified = dates['modified']
        _set_file_times(source, created, modified)


def controlled_environment(profile: Path) -> dict[str, str]:
    return {'PATH': '/usr/bin:/bin:/usr/sbin:/sbin', 'HOME': str(profile),
            'TMPDIR': str(profile / 'tmp'), 'LANG': 'en_US.UTF-8',
            'HTTP_PROXY': 'http://127.0.0.1:9', 'HTTPS_PROXY': 'http://127.0.0.1:9',
            'ALL_PROXY': 'http://127.0.0.1:9', 'NO_PROXY': 'localhost,127.0.0.1'}


def _identity(profile: Path, gui: Path, vault: Path) -> int:
    lock = profile / 'SingletonLock'
    match = re.search(r'-(\d+)$', os.readlink(lock))
    if not match or int(match.group(1)) <= 1:
        raise ValueError('invalid disposable Obsidian process lock')
    pid = int(match.group(1))
    command = subprocess.check_output(['/bin/ps', '-ww', '-p', str(pid), '-o', 'command='],
                                      env=controlled_environment(profile), text=True, stderr=subprocess.PIPE)
    arguments = shlex.split(command.strip())
    if (not arguments or Path(arguments[0]).resolve() != gui.resolve()
            or f'--user-data-dir={profile}' not in arguments or f'vault={vault.name}' not in arguments):
        raise ValueError('Obsidian process does not own the disposable profile and vault')
    return pid


class DesktopSession:
    def __init__(self, app_bundle: Path, profile: Path, vault: Path, deadline: float) -> None:
        self.app_bundle, self.profile, self.vault, self.deadline = app_bundle, profile, vault, deadline
        with (app_bundle / 'Contents/Info.plist').open('rb') as stream:
            info = plistlib.load(stream)
        executable = info.get('CFBundleExecutable')
        self.version = info.get('CFBundleShortVersionString')
        _version(self.version)
        if not isinstance(executable, str) or Path(executable).name != executable:
            raise ValueError('invalid Obsidian bundle executable')
        self.gui = app_bundle / 'Contents/MacOS' / executable
        self.cli = app_bundle / 'Contents/MacOS/obsidian-cli'
        if not self.gui.is_file() or not self.cli.is_file():
            raise ValueError('Obsidian bundle lacks the desktop or CLI executable')
        self.pid: int | None = None
        self.launched = False

    def start(self) -> None:
        (self.profile / 'tmp').mkdir()
        (self.profile / 'obsidian.json').write_text(json.dumps({
            'cli': True, 'frame': 'hidden', 'insider': False, 'updateDisabled': True,
            'vaults': {'devbookexport': {'path': str(self.vault), 'ts': 1760000000000, 'open': True}},
        }))
        (self.profile / 'devbookexport.json').write_text(json.dumps({
            'x': 120, 'y': 120, 'width': 1200, 'height': 850,
            'isMaximized': False, 'devTools': False, 'zoom': 0,
        }))
        environment = controlled_environment(self.profile)
        args = ['/usr/bin/open', '-na', str(self.app_bundle)]
        for name, value in environment.items():
            args.extend(['--env', f'{name}={value}'])
        args.extend(['--args', f'--user-data-dir={self.profile}', f'vault={self.vault.name}', *APP_FLAGS])
        # A timed-out launcher may still have started the app. Cleanup must prove
        # ownership before restoring files that a surviving renderer could read.
        self.launched = True
        subprocess.run(args, env=environment, capture_output=True, check=True, timeout=min(15, self.remaining()))
        while self.remaining() > 0:
            try:
                pid = _identity(self.profile, self.gui, self.vault)
                self.pid = pid
                if (self.profile / '.obsidian-cli.sock').exists():
                    self.verify_vault()
                    # Trust only the proven disposable profile and vault.
                    self.command('plugins:restrict', 'off')
                    self.verify_vault()
                    self.wait_native_index()
                    for plugin in PLUGINS:
                        self.command('plugin:enable', f'id={plugin}')
                    self.wait_plugins()
                    return
            except (FileNotFoundError, subprocess.CalledProcessError):
                pass
            time.sleep(min(0.25, self.remaining()))
        raise ValueError(f'disposable Obsidian {self.version} did not reach its identity and CLI readiness gates')

    def remaining(self) -> float:
        remaining = self.deadline - time.monotonic()
        if remaining <= 0:
            raise ValueError('desktop export deadline reached')
        return remaining

    def command(self, *arguments: str) -> str:
        if self.pid is None or _identity(self.profile, self.gui, self.vault) != self.pid:
            raise ValueError('disposable Obsidian process identity changed')
        read_fd, write_fd = os.pipe()
        try:
            # Match the official export helper: EOF can end native async CLI
            # handlers early. Retain a private writer without reading user stdin.
            return subprocess.check_output([str(self.cli), f'vault={self.vault.name}', *arguments],
                                           stdin=read_fd, env=controlled_environment(self.profile), text=True,
                                           stderr=subprocess.PIPE, timeout=self.remaining())
        finally:
            os.close(read_fd)
            os.close(write_fd)

    def verify_vault(self) -> None:
        registry = json.loads((self.profile / 'obsidian.json').read_text()).get('vaults', {})
        paths = [Path(row['path']).resolve() for row in registry.values()]
        if paths != [self.vault.resolve()]:
            raise ValueError('Obsidian registry includes a vault outside the disposable export')
        startup_error = 'Error: Command "eval" not found. It may require a plugin to be enabled.'
        while time.monotonic() < self.deadline:
            response = self.command('eval', 'code=JSON.stringify({vaultPath:app.vault.adapter.getBasePath()})')
            if response.strip() != startup_error:
                break
            time.sleep(min(0.25, max(0, self.deadline - time.monotonic())))
        else:
            raise ValueError('Obsidian CLI did not finish command registration: ' + startup_error)
        try:
            value = json.loads(response.strip().removeprefix('=> '))
            path = value['vaultPath']
        except (ValueError, TypeError, KeyError) as error:
            raise ValueError('Obsidian runtime vault identity response is invalid: ' + response[:240]) from error
        if not isinstance(path, str) or Path(path).resolve() != self.vault.resolve():
            raise ValueError('Obsidian runtime vault differs from the disposable export')

    def wait_native_index(self) -> None:
        # Syncer's initial cache observes native metadata/link resolution.
        # Loading it earlier can leave its fresh-vault cache waiting forever.
        probe = """JSON.stringify((()=>{
const files=app.vault.getMarkdownFiles().filter(f=>!f.path.split('/').some(p=>p.startsWith('.')));
return files.length>0&&files.every(f=>{
 const entry=app.metadataCache.fileCache[f.path];
 return entry?.size===f.stat.size&&entry?.mtime===f.stat.mtime&&
 Object.prototype.hasOwnProperty.call(app.metadataCache.resolvedLinks,f.path);
});})())"""
        while time.monotonic() < self.deadline:
            response = self.command('eval', f'code={probe}').strip().removeprefix('=> ')
            if response == 'true':
                return
            if response != 'false':
                raise ValueError('native metadata probe returned an invalid response: ' + response[:240])
            time.sleep(min(0.25, self.remaining()))
        raise ValueError('native metadata did not finish indexing before plugin startup')

    def wait_plugins(self) -> None:
        probe = """JSON.stringify({vaultPath:app.vault.adapter.getBasePath(),
plugins:Object.keys(app.plugins.plugins).sort(),
datacoreReady:app.plugins.plugins.datacore?.core?.initialized===true,
syncerLoaded:!!app.plugins.plugins['quartz-syncer'],
preserveSupported:JSON.stringify(app.setting.pluginTabs.find(t=>t.id==='quartz-syncer')?.getSettingDefinitions?.()??[]).includes('obsidianCommentMode')})"""
        last_status: dict[str, bool] = {'responseValid': False}
        while time.monotonic() < self.deadline:
            try:
                response = self.command('eval', f'code={probe}').strip().removeprefix('=> ')
                state = json.loads(response)
                if not isinstance(state, dict):
                    raise ValueError('unexpected readiness response')
                if state.get('vaultPath') != str(self.vault):
                    raise ValueError('plugin readiness probe returned a different vault')
                last_status = {name: state.get(name) is True for name in (
                    'syncerLoaded', 'preserveSupported', 'datacoreReady')}
                last_status['exactPlugins'] = state.get('plugins') == sorted(PLUGINS)
                if all(last_status.values()):
                    return
            except (json.JSONDecodeError, subprocess.CalledProcessError, subprocess.TimeoutExpired):
                last_status = {'responseValid': False}
            if time.monotonic() < self.deadline:
                time.sleep(min(0.5, self.remaining()))
        raise ValueError(f'Obsidian {self.version} plugins did not become ready before deadline; last status: {json.dumps(last_status, sort_keys=True)}')

    def wrapper(self, destination: Path) -> Path:
        # The official helper calls this executable instead of a global CLI.
        # Child processes inherit a deliberately constructed credential-free env.
        source = f'''#!{sys.executable}
import os, subprocess, sys, time
from pathlib import Path
sys.path.insert(0, {str(Path(__file__).resolve().parents[1])!r})
from devbook_improvement.desktop_export import _identity
if _identity(Path({str(self.profile)!r}), Path({str(self.gui)!r}), Path({str(self.vault)!r})) != {self.pid!r}: raise SystemExit("export process identity changed")
remaining = {self.deadline!r} - time.monotonic()
if remaining <= 0: raise SystemExit("desktop export deadline reached")
if not sys.argv[1:] or sys.argv[1] != {f'vault={self.vault.name}'!r}: raise SystemExit("wrong export vault")
result = subprocess.run([{str(self.cli)!r}, *sys.argv[1:]], env={controlled_environment(self.profile)!r}, timeout=remaining)
raise SystemExit(result.returncode)
'''
        destination.write_text(source)
        destination.chmod(0o700)
        return destination

    def close(self) -> None:
        if self.pid is None:
            if not self.launched:
                return
            try:
                self.pid = _identity(self.profile, self.gui, self.vault)
            except (FileNotFoundError, subprocess.CalledProcessError) as error:
                raise ValueError('cannot establish launched Obsidian ownership for cleanup') from error
        try:
            if _identity(self.profile, self.gui, self.vault) != self.pid:
                raise ValueError('refusing to stop an unowned Obsidian process')
        except (FileNotFoundError, subprocess.CalledProcessError) as error:
            try:
                os.kill(self.pid, 0)
            except ProcessLookupError:
                return
            raise ValueError('known Obsidian PID is alive but cleanup ownership cannot be proven') from error
        os.kill(self.pid, signal.SIGTERM)
        until = time.monotonic() + 5
        while time.monotonic() < until:
            try:
                os.kill(self.pid, 0)
            except ProcessLookupError:
                return
            time.sleep(0.1)
        if _identity(self.profile, self.gui, self.vault) != self.pid:
            raise ValueError('refusing to stop an unowned Obsidian process')
        os.kill(self.pid, signal.SIGKILL)
        until = time.monotonic() + 5
        while time.monotonic() < until:
            try:
                os.kill(self.pid, 0)
            except ProcessLookupError:
                return
            time.sleep(0.1)
        raise ValueError('owned Obsidian process did not stop before cleanup')


@contextlib.contextmanager
def _environment(values: Mapping[str, str]) -> Iterator[None]:
    previous = {name: os.environ.get(name) for name in values}
    os.environ.update(values)
    try:
        yield
    finally:
        for name, value in previous.items():
            if value is None:
                os.environ.pop(name, None)
            else:
                os.environ[name] = value


def _prepare_settings(original: Path, destination: Path) -> None:
    (destination / 'plugins').mkdir(parents=True)
    for plugin in PLUGINS:
        source = original / 'plugins' / plugin
        for name in BUNDLE_FILES:
            path = source / name
            if name != 'styles.css' and not path.is_file():
                raise ValueError(f'missing required export plugin bundle: {plugin}/{name}')
            if path.is_symlink():
                raise ValueError('export plugin bundles cannot be symlinks')
        target = destination / 'plugins' / plugin
        target.mkdir(exist_ok=True)
        for name in BUNDLE_FILES:
            if (source / name).is_file():
                shutil.copy2(source / name, target / name)
    (destination / 'community-plugins.json').write_text('[]')
    (destination / 'core-plugins.json').write_text(json.dumps(['canvas', 'bases']))
    (destination / 'app.json').write_text(json.dumps({
        'alwaysUpdateLinks': False, 'showUnsupportedFiles': True, 'defaultViewMode': 'preview',
    }))


def export_checkout(root: Path, expected_head: str, app_bundle: Path, timeout_seconds: int = 600) -> dict[str, Any]:
    """Stage verified outputs in a dedicated checkout; never commit or push."""
    root, app_bundle = root.resolve(), app_bundle.resolve()
    if sys.platform != 'darwin':
        raise ValueError('the isolated desktop exporter requires macOS')
    if not 1 <= timeout_seconds <= 1800:
        raise ValueError('desktop export timeout must be between 1 and 1800 seconds')
    if _git(root, 'rev-parse', 'HEAD').decode().strip() != expected_head:
        raise ValueError('checkout HEAD differs from expected PR head')
    if not _git(root, 'symbolic-ref', '--short', 'HEAD').decode().strip().startswith('notes/automated-'):
        raise ValueError('desktop export requires a managed notes/automated-* checkout')
    if _git(root, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('desktop export requires a clean dedicated checkout')
    source_hashes = _source_hashes(root)
    settings = root / 'Vault/.obsidian'
    if settings.is_symlink() or not settings.is_dir():
        raise ValueError('dedicated checkout must have a regular .obsidian directory')
    validate_app_version(app_bundle, settings)
    index = Path(os.fsdecode(_git(root, 'rev-parse', '--git-path', 'index')).strip())
    if not index.is_absolute():
        index = root / index
    temporary = Path(tempfile.mkdtemp(prefix='.desktop-export-', dir=root))
    profile = None
    try:
        backup = temporary / 'settings'
        # Darwin's CLI binds HOME/.obsidian-cli.sock, whose Unix socket path
        # must fit sockaddr_un.sun_path (104 bytes, including its terminator).
        profile = Path(tempfile.mkdtemp(prefix='db-export-', dir='/private/tmp'))
        if len(os.fsencode(profile / '.obsidian-cli.sock')) >= 104:
            raise ValueError('disposable Obsidian CLI socket path is too long')
        (temporary / 'recovery.json').write_text(json.dumps({'profile': str(profile), 'settings': str(backup)}))
        private_index = temporary / 'index'
        shutil.copy2(index, private_index)
        ignore = temporary / 'ignore'
        ignore.write_text('/Vault/.obsidian/**\n/.desktop-export-*/\n')
        environment = {**os.environ, 'GIT_INDEX_FILE': str(private_index), 'GIT_CONFIG_COUNT': '1',
                       'GIT_CONFIG_KEY_0': 'core.excludesFile', 'GIT_CONFIG_VALUE_0': str(ignore)}
        tracked = _git(root, 'ls-files', '-z', '--', 'Vault/.obsidian', env=environment)
        if tracked:
            subprocess.run(['git', 'update-index', '--skip-worktree', '-z', '--stdin'], cwd=root,
                           env=environment, input=tracked, check=True, capture_output=True)
        materialize_timestamps(root)
        session = DesktopSession(app_bundle, profile, root / 'Vault', time.monotonic() + timeout_seconds)
        settings.rename(backup)
        try:
            _prepare_settings(backup, settings)
            session.start()
            wrapper = session.wrapper(temporary / 'obsidian')
            with _environment({name: environment[name] for name in (
                'GIT_INDEX_FILE', 'GIT_CONFIG_COUNT', 'GIT_CONFIG_KEY_0', 'GIT_CONFIG_VALUE_0') } | {
                    'OBSIDIAN_BIN': str(wrapper), 'QUARTZ_SYNC_TIMEOUT': str(timeout_seconds)}):
                receipt = sync_export.export(root, expected_head)
            if _source_hashes(root) != source_hashes:
                raise ValueError('source changed during desktop export')
        finally:
            try:
                session.close()
            except (ValueError, OSError, subprocess.SubprocessError) as error:
                raise ValueError(f'{error}; original settings retained for recovery at {backup}; '
                                 f'isolated profile retained at {profile}') from error
            if settings.exists():
                shutil.rmtree(settings)
            backup.rename(settings)
        if _source_hashes(root) != source_hashes:
            raise ValueError('source changed during desktop export')
        changed = _git(root, 'diff', '--name-only', '--', 'Vault/.obsidian').strip()
        if changed:
            raise ValueError('original Obsidian settings were not restored exactly')
        outputs = [name for name in (*sync_export.OUTPUTS, sync_export.RECEIPT_PATH)
                   if (root / name).exists() or _git(root, 'ls-files', '--', name)]
        _git(root, 'add', '-A', '--', *outputs)
        sync_export.validate_receipt(receipt, sync_export._index_entries(root))
        return receipt
    finally:
        # A failed process-ownership check must not delete the original settings
        # or swap them underneath a still-running app. Preserve recovery data.
        if not (temporary / 'settings').exists():
            if profile is not None:
                shutil.rmtree(profile)
            shutil.rmtree(temporary)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode', choices=['export'])
    parser.add_argument('--expected-head', required=True)
    parser.add_argument('--app-bundle', type=Path, required=True)
    parser.add_argument('--timeout-seconds', type=int, default=600)
    arguments = parser.parse_args()
    root = Path(subprocess.check_output(['git', 'rev-parse', '--show-toplevel'], text=True).strip())
    try:
        export_checkout(root, arguments.expected_head, arguments.app_bundle, arguments.timeout_seconds)
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        parser.exit(1, f'{error}\n')
    print('Official desktop export and exact-source receipt staged; no commit or push performed.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
